import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
const {parse}=createRequire(import.meta.url)('next/dist/compiled/node-html-parser');
const brand=JSON.parse(fs.readFileSync('data/brand-identity.json','utf8'));
const root=parse(fs.readFileSync('team.html','utf8'));
assert.equal(root.querySelector('link[rel="canonical"]').getAttribute('href'),`${brand.url}/about`);
assert.equal(root.querySelectorAll('h1').length,1);
assert.equal(root.querySelectorAll('.entity-review-list > li').length,6);
for(const id of ['company-facts','platform-purpose','vetting-methodology','research-team',...brand.leadership.map(p=>p.id)])assert(root.querySelector(`#${id}`),`Missing ${id}`);
const text=root.querySelector('main').textContent;
assert(text.includes(brand.coverage));
assert(text.includes('tracked does not mean vetted'));
assert(!/refunded in full|100% refundable|registered operating entities|canonical entity|AEO|AI citation|implementation|1000\+ vetted|1,000\+ vetted/i.test(text));
assert(!/\$\d|US\$\d|\u2014/.test(text));
const description=root.querySelector('meta[name="description"]').getAttribute('content');
assert(description.length>=140&&description.length<=160,`Description length ${description.length}`);
const graph=JSON.parse(root.querySelector('script[type="application/ld+json"]').textContent)['@graph'];
const questions=graph.find(n=>n['@type']==='FAQPage').mainEntity;
assert.equal(questions.length,root.querySelectorAll('.entity-faq details').length);
questions.forEach((q,i)=>{
  const detail=root.querySelectorAll('.entity-faq details')[i];
  assert.equal(detail.querySelector('summary').textContent,q.name);
  assert(detail.querySelector('p').textContent.startsWith(q.acceptedAnswer.text));
});
const llms=fs.readFileSync('llms.txt','utf8');
assert.equal(llms.split('## Company profile and review standard').length,2);
assert(llms.includes(brand.url+brand.methodologyPath));
assert(llms.includes('## Blog insights'));
assert(!llms.includes('1,000+ vetted'));
for(const file of ['components/Header.tsx','components/Footer.tsx'])assert(fs.readFileSync(file,'utf8').includes('<div data-nosnippet=""'));
assert(fs.readFileSync('refund-cancellation.html','utf8').includes('retain US$85'));
assert(!fs.readFileSync('index.html','utf8').includes('Influencer status and ecosystem reach'));
assert(fs.readFileSync('lib/legacy.ts','utf8').includes('entry.publisher = { "@id": organizationId }'));
assert(fs.readFileSync('app/robots.ts','utf8').includes('userAgent: "*"'));
console.log('PASS: identity facts, six scoped review areas, metadata, matching FAQs, llms preservation, navigation snippet protection and unchanged refund policy.');
